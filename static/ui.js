function applyLanguage(lang) {
    const dict = i18nDictionary[lang];
    document.documentElement.lang = lang === "en" ? "en" : "zh-TW";
    document.title = dict[document.body.dataset.pageTitle] + " | " + dict.nav_brand;
    for (const [attribute, property] of [["data-i18n", "textContent"], ["data-i18n-ph", "placeholder"]]) {
        document.querySelectorAll("[" + attribute + "]").forEach(element => {
            const text = dict[element.getAttribute(attribute)];
            if (text !== undefined) element[property] = text;
        });
    }
    document.querySelectorAll("[data-i18n-label]").forEach(element => {
        element.setAttribute("aria-label", dict[element.dataset.i18nLabel]);
    });
    document.querySelectorAll(".lang-toggle").forEach(button => {
        button.textContent = lang === "zh" ? "English" : "中文";
        button.lang = lang === "zh" ? "en" : "zh-TW";
    });
    document.dispatchEvent(new Event("languagechange"));
}

let currentLanguage = "zh";
try {
    if (localStorage.getItem("app_lang") === "en") currentLanguage = "en";
} catch { /* The switch still works when storage is unavailable. */ }
applyLanguage(currentLanguage);
document.querySelectorAll(".lang-toggle").forEach(button => {
    button.addEventListener("click", () => {
        currentLanguage = currentLanguage === "zh" ? "en" : "zh";
        applyLanguage(currentLanguage);
        try { localStorage.setItem("app_lang", currentLanguage); } catch {}
    });
});

function setupBoxSearch() {
    const input = document.getElementById("boxSearch");
    const grid = document.getElementById("boxGrid");
    if (!grid) return;

    const cards = [...grid.querySelectorAll(".box-card")].map(card => ({
        element: card,
        searchText: card.dataset.boxSearch.toLowerCase(),
        items: [...card.querySelectorAll("[data-item-search]")].map(item => ({
            element: item, searchText: item.dataset.itemSearch.toLowerCase()
        })),
        count: card.querySelector("[data-preview-count]"),
        more: card.querySelector(".preview-more"),
        rest: card.querySelector("[data-preview-rest]")
    }));
    const count = document.getElementById("boxResultCount");
    const empty = document.getElementById("boxNoResults");

    function updateResults() {
        const query = input.value.trim().toLowerCase();
        let matches = 0;
        for (const card of cards) {
            const wholeBox = card.searchText.includes(query);
            let itemMatches = 0;
            for (const item of card.items) {
                const match = wholeBox || item.searchText.includes(query);
                if (match) itemMatches++;
                item.element.hidden = !match || itemMatches > 3;
            }
            card.element.hidden = !wholeBox && itemMatches === 0;
            if (!card.element.hidden) matches++;
            card.count.textContent = itemMatches;
            if (card.more) {
                card.more.hidden = itemMatches <= 3;
                card.rest.textContent = Math.max(0, itemMatches - 3);
            }
        }
        count.textContent = matches;
        empty.hidden = matches > 0;
    }

    input.addEventListener("input", updateResults);
    window.addEventListener("pageshow", updateResults);
}

function setupPhotoPreview() {
    const modal = document.getElementById("imagePreviewModal");
    if (!modal) return;
    const title = modal.querySelector("[data-photo-title]");
    const image = modal.querySelector("[data-preview-photo]");

    modal.addEventListener("show.bs.modal", event => {
        const photo = event.relatedTarget;
        if (!photo?.dataset.photo) return;
        title.textContent = photo.dataset.equipment;
        image.src = photo.dataset.photo;
        image.alt = photo.dataset.equipment;
    });
}

setupBoxSearch();
setupPhotoPreview();

